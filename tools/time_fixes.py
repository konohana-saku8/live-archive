"""突击直播的时间戳校正表。

数据库里的 `TranslationHistory.Timestamp` 是机器记录，不改；导出时按这张表把
「录播转写导致的时间戳偏移」校准回真实直播时间。只影响指定时段的记录。

依据（2026-11-22 16:33 突击场）：
- 手机 live-capture 库的 room_event 记 live 于 16:33:08，SC 从 16:35:48 到 17:28:05；
  而翻译库这一段的记录是 19:26:28–20:20:25，两个时钟不同源。
- 12 个 SC 内容锚点（她口播某条 SC 的时刻 − 该 SC 的 start_time）落在
  2:52:29–2:54:04；口播晚于 SC 到达是正常的，故取区间下沿附近的 2:52:30。
- 用 2:52:30 校准：首条 19:26:28 → 16:33:58（开播后 50 秒开口），
  末条 20:20:25 → 17:27:55（最后一条 SC 17:28:05 之后、下播前），两端都吻合。

格式：(起始 epoch 秒, 结束 epoch 秒（含）, 偏移秒数, 说明)。
"""

# 2026-11-22 19:25:00–20:21:00（原始时钟）整体回拨 10350 秒 = 2 小时 52 分 30 秒
SHIFTS = [
    (1795346700, 1795350060, -10350, '2026-11-22 突击场：录播转写时间戳回拨 2:52:30'),
]


def apply(ts):
    """把原始 Timestamp（秒）校准到真实直播时间；不在校正区间就原样返回。

    入参可能是 int（数据库 Timestamp）或 float（SpeechStart 的开口时刻），
    后者要保留小数部分，否则字幕的精确起点会被截掉。
    """
    t = int(ts)
    for lo, hi, delta, _note in SHIFTS:
        if lo <= t <= hi:
            return ts + delta
    return ts
