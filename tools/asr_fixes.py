# -*- coding: utf-8 -*-
"""ASR / 机器译文的定点校正表。

数据库里的 `TranslationHistory` 是机器记录，不改；导出成场次逐字稿与字幕轨时，
按这张表把「听错、译错，意思已经变了」的硬错替换掉（人名、专名、同音词）。
润色、换措辞、口语改书面语一律不做。

每条都写清校勘依据：原文是什么、正确是什么、凭什么这么判断。
只写能唯一命中的长串，不要写「患者」这种单独一个词，免得误伤正常用词。
"""

FIXES = [
    # 2026-11-20 01:01:37 下播前的致谢。她念的是「艦長になってくれた人」——B 站舰长是
    # 付费订阅，正接后面的「ギフトくれた人、コメントしてくれた人」；ASR 听成「患者を
    # なってくれた人」，机器译文跟着译成「成为我患者的人」。
    ('患者をなってくれた人', '艦長になってくれた人'),
    ('成为我患者的人', '上了我舰长的人'),

    # 2026-10-23 00:36:00 观众问「如果能回到过去想对以前的自己说什么」。她说的是
    # 「過去に戻りたいと思ったこと一切ない」（从没想过要回到过去），下一句 00:36:08
    # 「私過去に戻りたいことって何にもないんですよ」是同义重复、ASR 正确识别成「戻りたい」。
    # 前一句把「戻りたい」（想回去）听成「踊りたい」（想跳舞），机翻跟着译成「在过去跳舞」。
    # 摘录 10-23 那条当初已人工校订为「戻りたい」，这里让逐字稿与字幕跟上。
    ('過去に踊りたいと思うことって一切ないんだよね', '過去に戻りたいと思うことって一切ないんだよね'),
    ('我从来都不曾想过要在过去跳舞呢', '我从来没有想过要回到过去呢'),

    # 2026-11-24 00:23:31 专名 ASR 误识。前面几句一直在说「うちの神社」，这里同一座
    # 被听成别的名字；机翻也跟着错。按前文说法还原。
    ('イサナ神社は神子さんに常に給料出せないから',
     'うちの神社は神子さんに常に給料出せないから'),
    ('伊邪那神社没法一直给巫女发工资',
     '我们神社没法一直给巫女发工资'),
]


def apply(text):
    """把一条日文原文或中文译文按表校正。没有命中就原样返回。"""
    if not text:
        return text
    for bad, good in FIXES:
        if bad in text:
            text = text.replace(bad, good)
    return text
